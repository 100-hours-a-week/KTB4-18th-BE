CREATE TABLE music_search_ingest_jobs (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    provider VARCHAR(30) NOT NULL,
    external_music_id VARCHAR(64) NOT NULL,
    title VARCHAR(255) NOT NULL,
    artist_name VARCHAR(1000) NOT NULL,
    album_cover_url VARCHAR(1000) NULL,
    preview_url VARCHAR(1000) NULL,
    youtube_video_id VARCHAR(32) NULL,
    title_us VARCHAR(255) NULL,
    artist_name_us VARCHAR(1000) NULL,
    title_ko VARCHAR(255) NULL,
    artist_name_ko VARCHAR(1000) NULL,
    release_epoch_second BIGINT NULL,
    status VARCHAR(16) NOT NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    next_attempt_at DATETIME(6) NOT NULL,
    lease_token CHAR(36) NULL,
    lease_until DATETIME(6) NULL,
    last_error_code VARCHAR(80) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT uq_music_search_ingest_jobs_provider_external UNIQUE (provider, external_music_id),
    INDEX idx_music_search_ingest_jobs_due (status, next_attempt_at, id),
    INDEX idx_music_search_ingest_jobs_lease (status, lease_until, id)
) ENGINE=InnoDB;
